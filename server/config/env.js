/**
 * Read environment variables from .env and gather them into a single config object.
 * Other files import `config` instead of reading process.env directly.
 */
import 'dotenv/config';

/** Parse a string as an integer, returning the default value when invalid */
const toInt = (value, fallback) => {
  const n = Number.parseInt(value, 10);
  return Number.isNaN(n) ? fallback : n;
};

export const config = Object.freeze({
  env: process.env.NODE_ENV || 'development',
  isProd: process.env.NODE_ENV === 'production',
  port: toInt(process.env.PORT, 3000),

  db: {
    host: process.env.DB_HOST || '127.0.0.1',
    port: toInt(process.env.DB_PORT, 3306),
    user: process.env.DB_USER || 'root',
    password: process.env.DB_PASSWORD ?? '',
    database: process.env.DB_NAME || 'market_c2c',
  },

  /**
   * Frontend origins allowed to call the API with cookies (CORS).
   * Several origins separated by commas, e.g. "https://market-c2c.test,https://localhost:5500"
   */
  corsOrigins: (process.env.CORS_ORIGINS || 'https://market-c2c.test')
    .split(',')
    .map((origin) => origin.trim().replace(/\/+$/, ''))
    .filter(Boolean),

  /**
   * HTTPS certificate for the API. Defaults to the certificate generated by Laragon
   * (it already covers *.test and is trusted by Windows once SSL is enabled in Laragon).
   */
  ssl: {
    certFile: process.env.SSL_CERT || 'D:/laragon/etc/ssl/laragon.crt',
    keyFile: process.env.SSL_KEY || 'D:/laragon/etc/ssl/laragon.key',
  },

  session: {
    cookieName: 'mc2c.sid',
    secret: process.env.SESSION_SECRET || 'market-c2c-dev-secret',
    maxAgeMs: toInt(process.env.SESSION_MAX_AGE_HOURS, 24) * 60 * 60 * 1000,
  },
});
